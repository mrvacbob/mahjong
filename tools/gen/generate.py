def gen_agari(rng, out):
    e = Emitter(os.path.join(out, "agari.txt"), "ag", "agari", ["agari: is the hand complete, and its decompositions."])
    e.section("random complete hands, mixed styles, 0-4 melds")
    for _ in guard(e, 800):
        b, st = any_built(rng)
        e.emit(hm(b.concealed(), b.melds))
    e.section("single-suit complete hands (many decompositions)")
    target = e.count + 280
    for _ in guard(e, target):
        b = style_build(rng, "chinitsu")
        if b is None:
            continue
        if rng.random() < 0.7:
            assign_melds(rng, b, 0, 0)
        e.emit(hm(b.concealed(), b.melds))
    target = e.count + 30
    for _ in guard(e, target):
        b = build_chuuren(rng)
        e.emit(hm(b.concealed(), []))
    e.section("chiitoi and ryanpeikou shapes")
    target = e.count + 120
    for _ in guard(e, target):
        b = build_chiitoi(rng, dup_seq=rng.random() < 0.5)
        if b:
            e.emit(hm(b.concealed(), []))
    e.section("kokushi, complete and one tile off")
    target = e.count + 13
    for _ in guard(e, target):
        b = build_kokushi(rng)
        e.emit(hm(b.concealed(), []))
    target = e.count + 25
    for _ in guard(e, target):
        b = build_kokushi(rng)
        e.emit(hm(perturb(rng, b.concealed(), b.pool, 1), []))
    e.section("complete hands with one or two tiles replaced (mostly not complete)")
    target = e.count + 420
    for _ in guard(e, target):
        b, st = any_built(rng)
        conc = perturb(rng, b.concealed(), b.pool, rng.choice([1, 1, 1, 2]))
        e.emit(hm(conc, b.melds))
    e.section("random single-suit tiles")
    target = e.count + 150
    for _ in guard(e, target):
        s = rng.randrange(3)
        nm = rng.choices([0, 1, 2], [70, 20, 10])[0]
        pool = Pool(rng)
        melds = []
        for _ in range(nm):
            k = rng.randrange(9) + 9 * s
            if pool.can(k, 3):
                melds.append(("p", [pool.take(k) for _ in range(3)]))
        tiles, _ = random_tiles(rng, 14 - 3 * len(melds), kinds=range(9 * s, 9 * s + 9), pool=pool)
        e.emit(hm(tiles, melds))
    e.section("random tiles")
    target = e.count + 150
    for _ in guard(e, target):
        tiles, _ = random_tiles(rng, 14)
        e.emit(hm(tiles, []))
    emit_test_requests(e, "agari")
    e.write()
    return e


