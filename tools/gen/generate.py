def win_picker(name):
    if name == "pair":
        def pick(conc):
            c = counts34(conc)
            idx = [i for i, t in enumerate(conc) if c[kind(t)] == 2]
            return idx[0] if idx else None
        return pick
    if name == "kokushi_pair":
        def pick(conc):
            c = counts34(conc)
            return next(i for i, t in enumerate(conc) if c[kind(t)] == 2)
        return pick
    if name == "kokushi_single":
        def pick(conc):
            c = counts34(conc)
            idx = [i for i, t in enumerate(conc) if c[kind(t)] == 1]
            return idx[len(idx) // 2] if idx else None
        return pick
    if name == "chuuren_junsei":
        def pick(conc):
            c = counts34(conc)
            s = kind(conc[0]) // 9 * 9
            base = [3, 1, 1, 1, 1, 1, 1, 1, 3]
            extra = [d for d in range(9) if c[s + d] > base[d]]
            return next(i for i, t in enumerate(conc) if kind(t) == s + extra[0])
        return pick
    raise ValueError(name)


def target_built(rng, style):
    if style is None:
        return any_built(rng)[0]
    if style == "closed":
        for _ in range(100):
            b = style_build(rng, rng.choice(CLOSED_STYLES))
            if b is not None and b.is_closed():
                return b
        return None
    if style == "closed0":
        for _ in range(100):
            b = style_build(rng, rng.choice(CLOSED_STYLES + ["suuankou", "chiitoi", "kokushi", "chuuren"]))
            if b is not None and not b.melds:
                return b
        return None
    return style_build(rng, style, red_bias=2.0)


def gen_score(rng, out):
    e = Emitter(os.path.join(out, "score.txt"), "sc", "score", [
        "score: yaku, han/fu or yakuman, payments.",
    ])

    e.section("targeted: every yaku in the spec's list (each case contains the named yaku)")
    for name, (style, kwargs) in YAKU_TARGETS.items():
        got = 0
        for _ in range(4000):
            if got >= 22:
                break
            b = target_built(rng, style)
            if b is None:
                continue
            kw = dict(kwargs)
            if name in ("yakuhai_seat", "yakuhai_round"):
                ws = [g[1] for g in b.groups if g[0] == "trip" and g[1] in WINDS_K]
                ws += [kind(m[1][0]) for m in b.melds if kind(m[1][0]) in WINDS_K]
                if not ws:
                    continue
                w = WINDS[ws[0] - 27]
                kw["seat" if name == "yakuhai_seat" else "rnd"] = w
            if "win_pick" in kw:
                kw["win_pick"] = win_picker(kw["win_pick"])
            pairs = score_case(rng, b, **kw)
            if pairs is None:
                continue
            body = fmt_request("x", "score", pairs)
            out_, info = O.score(parse_request(body)[2])
            ystr = dict(out_).get("yaku", "")
            if name not in [y.split(":")[0] for y in ystr.split(",") if y]:
                continue
            if e.emit(pairs, comments=[f"target: {name}"] if got == 0 else ()) is not None:
                got += 1
        if got < 22:
            print(f"warning: only {got} cases for yaku {name}", file=sys.stderr)

    e.section("targeted: every yakuman in the spec's list")
    for name, (style, kwargs) in YAKUMAN_TARGETS.items():
        got = 0
        for _ in range(4000):
            if got >= 14:
                break
            b = target_built(rng, style)
            if b is None:
                continue
            kw = dict(kwargs)
            if "win_pick" in kw:
                kw["win_pick"] = win_picker(kw["win_pick"])
            pairs = score_case(rng, b, **kw)
            if pairs is None:
                continue
            out_, info = O.score(parse_request(fmt_request("x", "score", pairs))[2])
            ystr = dict(out_).get("yaku", "")
            if name not in [y.split(":")[0] for y in ystr.split(",") if y]:
                continue
            if e.emit(pairs, comments=[f"target: {name}"] if got == 0 else ()) is not None:
                got += 1
        if got < 14:
            print(f"warning: only {got} cases for yakuman {name}", file=sys.stderr)

    e.section("fu edge cases: kans, closed/open triplets, waits, pinfu tsumo/ron, open no-fu hands, wind pairs")
    target = e.count + 450
    for _ in guard(e, target):
        r = rng.random()
        if r < 0.25:
            b = style_build(rng, "kankan")
        elif r < 0.4:
            b = style_build(rng, "pinfu")
        elif r < 0.55:
            b = style_build(rng, "openseq")
        elif r < 0.7:
            b = style_build(rng, "toitoi")
        else:
            # pair of a wind; often seat == round == pair wind (double wind)
            w = rng.choice(WINDS_K)
            b = build(rng, pair_kind=w, seq_prob=0.6)
            if b is None:
                continue
            o, a = random_meld_counts(rng)
            assign_melds(rng, b, o, a)
            pairs = score_case(rng, b, seat=WINDS[w - 27], rnd=WINDS[w - 27] if rng.random() < 0.7 else None)
            if pairs:
                e.emit(pairs)
            continue
        if b is None:
            continue
        pairs = score_case(rng, b, no_random_flags=rng.random() < 0.5)
        if pairs:
            e.emit(pairs)

    e.section("not complete (error=not_agari)")
    target = e.count + 200
    for _ in guard(e, target):
        b, _ = any_built(rng)
        if b.special:
            continue
        conc = perturb(rng, b.concealed(), b.pool, 1)
        b.fixed_tiles = conc
        pairs = score_case(rng, b)
        if pairs:
            e.emit(pairs)

    e.section("complete but no yaku (error=no_yaku) and near misses")
    target = e.count + 250
    tries = 0
    for _ in guard(e, target):
        tries += 1
        b, _ = any_built(rng, style=rng.choice(["any", "openseq", "toitoi", "any"]))
        pairs = score_case(rng, b, no_random_flags=True, by=rng.choice(["ron", "ron", "tsumo"]))
        if not pairs:
            continue
        out_, _ = O.score(parse_request(fmt_request("x", "score", pairs))[2])
        if dict(out_).get("error") == "no_yaku" or rng.random() < 0.05:
            e.emit(pairs)

    e.section("random hands, random context")
    target = e.count + 3150
    for _ in guard(e, target):
        b, _ = any_built(rng, red_bias=rng.choice([1.0, 1.0, 2.5]))
        pairs = score_case(rng, b)
        if not pairs:
            continue
        out_, _ = O.score(parse_request(fmt_request("x", "score", pairs))[2])
        if dict(out_).get("error") == "no_yaku" and rng.random() < 0.75:
            continue  # the no_yaku section already covers these
        e.emit(pairs)

    emit_test_requests(e, "score")
    e.write()
    return e


# ---------------------------------------------------------------- main


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--seed", type=int, default=20261126)
    ap.add_argument("--out", default=os.path.join(ROOT, "corpus"))
    ap.add_argument("--only", action="append", choices=["agari", "shanten", "waits", "score"])
    args = ap.parse_args()
    gens = {"agari": gen_agari, "shanten": gen_shanten, "waits": gen_waits, "score": gen_score}
    for i, (name, fn) in enumerate(gens.items()):
        if args.only and name not in args.only:
            continue
        rng = random.Random(f"{args.seed}:{name}")
        e = fn(rng, args.out)
        extra = ""
        if name == "score":
            extra = f", dropped {e.dropped_ambiguous} ambiguous"
        extra += f", {e.rule_sensitive} rule-sensitive notes"
        print(f"{name}: {e.count} cases{extra}")
        stats = sorted(e.stats.items(), key=lambda kv: (-kv[1], kv[0]))
        print("   " + ", ".join(f"{k} {v}" for k, v in stats))


if __name__ == "__main__":
    main()
