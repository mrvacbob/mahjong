def suit_ok(s, honors=False):
    def ok(gt, k):
        ks = [k, k + 1, k + 2] if gt == "seq" else [k]
        return all(x // 9 == s and x < 27 or (honors and x >= 27) for x in ks)

    return ok


def style_build(rng, name, red_bias=1.0):
    """-> Built with melds assigned, or None."""
    closed_only = False
    keep = set()
    force_kans = 0
    n_open = n_ankan = None
    kw = dict(red_bias=red_bias)
    if name == "any":
        b = build(rng, **kw)
    elif name == "tanyao":
        b = build(rng, group_ok=lambda gt, k: all(is_simple(x) for x in ([k, k + 1, k + 2] if gt == "seq" else [k])),
                  pair_ok=is_simple, **kw)
    elif name == "pinfu":
        b = build(rng, seq_prob=1.0, pair_ok=lambda k: k < 27 or k == 30, **kw)
        closed_only = True
        n_ankan = 0
    elif name == "openseq":
        b = build(rng, seq_prob=1.0, pair_ok=lambda k: k < 27, **kw)
        n_open = rng.randint(1, 4)
        n_ankan = 0
    elif name == "honitsu":
        s = rng.randrange(3)
        b = build(rng, group_ok=suit_ok(s, True), pair_ok=lambda k: k >= 27 or k // 9 == s, seq_prob=0.5, **kw)
    elif name == "chinitsu":
        s = rng.randrange(3)
        b = build(rng, group_ok=suit_ok(s), pair_ok=lambda k: k < 27 and k // 9 == s, seq_prob=0.65, **kw)
    elif name == "toitoi":
        b = build(rng, seq_prob=0.0, **kw)
    elif name == "chanta":
        b = build(rng, group_ok=lambda gt, k: (k % 9 in (0, 6) and k < 27) if gt == "seq" else k in YAOCHU,
                  pair_ok=lambda k: k in YAOCHU, seq_prob=0.6, **kw)
    elif name == "junchan":
        b = build(rng, group_ok=lambda gt, k: (k % 9 in (0, 6) and k < 27) if gt == "seq" else k in TERMINALS,
                  pair_ok=lambda k: k in TERMINALS, seq_prob=0.6, **kw)
    elif name == "honroutou":
        b = build(rng, seq_prob=0.0, group_ok=lambda gt, k: k in YAOCHU, pair_ok=lambda k: k in YAOCHU, **kw)
    elif name == "yakuhai":
        k = rng.choice(DRAGONS + WINDS_K)
        b = build(rng, req=[("trip", k)], **kw)
    elif name == "iipeikou":
        s = rng.choice([x for x in range(27) if x % 9 <= 6])
        b = build(rng, req=[("seq", s), ("seq", s)], **kw)
        closed_only = True
    elif name == "ryanpeikou":
        s1 = rng.choice([x for x in range(27) if x % 9 <= 6])
        s2 = rng.choice([x for x in range(27) if x % 9 <= 6])
        b = build(rng, req=[("seq", s1), ("seq", s1), ("seq", s2), ("seq", s2)], **kw)
        closed_only = True
        n_ankan = 0
    elif name == "sanshoku":
        d = rng.randrange(7)
        b = build(rng, req=[("seq", d), ("seq", 9 + d), ("seq", 18 + d)], **kw)
    elif name == "sanshoku_doukou":
        d = rng.randrange(9)
        b = build(rng, req=[("trip", d), ("trip", 9 + d), ("trip", 18 + d)], **kw)
    elif name == "ittsu":
        s = rng.randrange(3) * 9
        b = build(rng, req=[("seq", s), ("seq", s + 3), ("seq", s + 6)], **kw)
    elif name == "shousangen":
        d = list(DRAGONS)
        rng.shuffle(d)
        b = build(rng, req=[("trip", d[0]), ("trip", d[1])], pair_kind=d[2], **kw)
    elif name == "daisangen":
        b = build(rng, req=[("trip", 31), ("trip", 32), ("trip", 33)], **kw)
    elif name == "shousuushii":
        w = list(WINDS_K)
        rng.shuffle(w)
        b = build(rng, req=[("trip", w[0]), ("trip", w[1]), ("trip", w[2])], pair_kind=w[3], **kw)
    elif name == "daisuushii":
        b = build(rng, req=[("trip", k) for k in WINDS_K], **kw)
    elif name == "tsuuiisou":
        b = build(rng, seq_prob=0.0, group_ok=lambda gt, k: k in HONORS, pair_ok=lambda k: k in HONORS, **kw)
    elif name == "chinroutou":
        b = build(rng, seq_prob=0.0, group_ok=lambda gt, k: k in TERMINALS, pair_ok=lambda k: k in TERMINALS, **kw)
    elif name == "ryuuiisou":
        b = build(rng, seq_prob=0.4, group_ok=lambda gt, k: (k == 19) if gt == "seq" else k in GREEN,
                  pair_ok=lambda k: k in GREEN, **kw)
    elif name == "sanankou":
        ks = rng.sample(range(34), 3)
        b = build(rng, req=[("trip", k) for k in ks], **kw)
        keep = {0, 1, 2} if rng.random() < 0.7 else {0, 1}
        n_ankan = 0 if 2 in keep else 1
    elif name == "suuankou":
        ks = rng.sample(range(34), 4)
        b = build(rng, req=[("trip", k) for k in ks], **kw)
        closed_only = True
    elif name == "sankantsu":
        b = build(rng, seq_prob=0.3, req=[("trip", k) for k in rng.sample(range(34), 3)], **kw)
        if b:
            na = rng.randint(0, 3)
            assign_melds(rng, b, n_open=3 - na + rng.randint(0, 1), n_ankan=na, kan_prob=0.0, force_kans=3)
            return b if b.n_kans() >= 3 else None
    elif name == "suukantsu":
        b = build(rng, seq_prob=0.0, **kw)
        if b:
            na = rng.randint(0, 4)
            assign_melds(rng, b, n_open=4 - na, n_ankan=na, kan_prob=1.0, force_kans=4)
            return b if b.n_kans() == 4 else None
    elif name == "kankan":  # lots of kans for fu variety
        b = build(rng, seq_prob=0.25, **kw)
        if b:
            assign_melds(rng, b, n_open=rng.randint(0, 3), n_ankan=rng.randint(0, 3), kan_prob=0.6)
            return b
    elif name == "chiitoi":
        r = rng.random()
        if r < 0.15:
            return build_chiitoi(rng, dup_seq=True, red_bias=red_bias)
        if r < 0.3:
            return build_chiitoi(rng, kinds_ok=lambda k: k in YAOCHU)
        if r < 0.4:
            return build_chiitoi(rng, kinds_ok=lambda k: k in HONORS or k // 9 == 1)
        if r < 0.5:
            return build_chiitoi(rng, kinds_ok=is_simple, red_bias=red_bias)
        return build_chiitoi(rng, red_bias=red_bias)
    elif name == "kokushi":
        return build_kokushi(rng)
    elif name == "chuuren":
        return build_chuuren(rng)
    else:
        raise ValueError(name)
    if b is None:
        return None
    if n_open is None or n_ankan is None:
        o, a = random_meld_counts(rng, closed_only)
        n_open = o if n_open is None else n_open
        n_ankan = a if n_ankan is None else n_ankan
    if closed_only:
        n_open = 0
    assign_melds(rng, b, n_open=n_open, n_ankan=n_ankan, keep=keep, force_kans=force_kans)
    return b


STYLE_WEIGHTS = {
    "any": 30, "tanyao": 10, "pinfu": 8, "openseq": 5, "honitsu": 6, "chinitsu": 5, "toitoi": 5, "chanta": 3,
    "junchan": 2, "honroutou": 1, "yakuhai": 9, "iipeikou": 3, "ryanpeikou": 1, "sanshoku": 2,
    "sanshoku_doukou": 1, "ittsu": 2, "shousangen": 1, "daisangen": 0.4, "shousuushii": 0.3, "daisuushii": 0.2,
    "tsuuiisou": 0.3, "chinroutou": 0.2, "ryuuiisou": 0.3, "sanankou": 2, "suuankou": 0.6, "sankantsu": 0.6,
    "suukantsu": 0.2, "kankan": 2, "chiitoi": 5, "kokushi": 0.6, "chuuren": 0.4,
}


def random_style(rng):
    names = list(STYLE_WEIGHTS)
    return rng.choices(names, [STYLE_WEIGHTS[n] for n in names])[0]


def any_built(rng, red_bias=1.0, style=None):
    for _ in range(100):
        st = style or random_style(rng)
        b = style_build(rng, st, red_bias)
        if b is not None:
            return b, st
    raise RuntimeError("could not build")


