def gen_shanten(rng, out):
    e = Emitter(os.path.join(out, "shanten.txt"), "sh", "shanten", ["shanten: standard / chiitoi / kokushi shanten."])
    e.section("complete hands (14-3k tiles)")
    for _ in guard(e, 150):
        b, _ = any_built(rng)
        e.emit(hm(b.concealed(), b.melds))
    e.section("complete hands minus one tile (13-3k, tenpai or better)")
    target = e.count + 400
    for _ in guard(e, target):
        b, _ = any_built(rng)
        c = b.concealed()
        c.pop(rng.randrange(len(c)))
        e.emit(hm(c, b.melds))
    e.section("complete hands with 1-3 tiles replaced (14-3k)")
    target = e.count + 300
    for _ in guard(e, target):
        b, _ = any_built(rng)
        e.emit(hm(perturb(rng, b.concealed(), b.pool, rng.randint(1, 3)), b.melds))
    e.section("complete hands minus one tile, then 1-4 tiles replaced (13-3k)")
    target = e.count + 400
    for _ in guard(e, target):
        b, _ = any_built(rng)
        c = b.concealed()
        t = c.pop(rng.randrange(len(c)))
        b.pool.counts[kind(t)] -= 1
        b.pool.red_used.discard(t)
        e.emit(hm(perturb(rng, c, b.pool, rng.randint(1, 4)), b.melds))
    e.section("pair-heavy hands (chiitoi shanten)")
    target = e.count + 150
    for _ in guard(e, target):
        b = build_chiitoi(rng, dup_seq=rng.random() < 0.2)
        if not b:
            continue
        c = perturb(rng, b.concealed(), b.pool, rng.randint(1, 4))
        if rng.random() < 0.5:
            c.pop(rng.randrange(len(c)))
        e.emit(hm(c, []))
    e.section("terminal/honor-heavy hands (kokushi shanten)")
    target = e.count + 100
    for _ in guard(e, target):
        b = build_kokushi(rng)
        c = perturb(rng, b.concealed(), b.pool, rng.randint(0, 5))
        if rng.random() < 0.6:
            c.pop(rng.randrange(len(c)))
        e.emit(hm(c, []))
    e.section("single-suit hands")
    target = e.count + 200
    for _ in guard(e, target):
        s = rng.randrange(3)
        n = rng.choice([13, 14])
        tiles, _ = random_tiles(rng, n, kinds=range(9 * s, 9 * s + 9))
        e.emit(hm(tiles, []))
    e.section("random tiles, 13 or 14, sometimes with melds")
    target = e.count + 300
    for _ in guard(e, target):
        pool = Pool(rng)
        melds = []
        for _ in range(rng.choices([0, 1, 2, 3], [70, 15, 10, 5])[0]):
            k = rng.randrange(34)
            if pool.can(k, 3):
                melds.append(("p", [pool.take(k) for _ in range(3)]))
        n = rng.choice([13, 14]) - 3 * len(melds)
        tiles, _ = random_tiles(rng, n, pool=pool)
        e.emit(hm(tiles, melds))
    e.section("hands holding all four copies of a kind")
    target = e.count + 120
    for _ in guard(e, target):
        pool = Pool(rng)
        k = rng.randrange(34)
        tiles = [pool.take(k) for _ in range(4)]
        if rng.random() < 0.5:
            k2 = rng.randrange(34)
            if pool.can(k2, 4):
                tiles += [pool.take(k2) for _ in range(4)]
        near = [x for x in range(34) if abs(x - k) <= 3 and (x < 27) == (k < 27)]
        n = rng.choice([13, 14])
        while len(tiles) < n:
            if rng.random() < 0.6:
                try:
                    tiles.append(pool.random_tile(near))
                    continue
                except ValueError:
                    pass
            tiles.append(pool.random_tile())
        e.emit(hm(tiles, []))
    emit_test_requests(e, "shanten")
    e.write()
    return e


