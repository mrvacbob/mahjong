def score_case(rng, b, *, by=None, flags_force=(), seat=None, rnd=None, win_pick=None, honba=None,
               no_random_flags=False):
    """-> request pairs, or None if the forced constraints can't hold."""
    conc = b.concealed()
    closed = b.is_closed()
    melds = b.melds
    if win_pick is None:
        wi = rng.randrange(len(conc))
    else:
        wi = win_pick(conc)
        if wi is None:
            return None
    win = conc[wi]
    hand = conc[:wi] + conc[wi + 1:]
    all_tiles = conc + meld_tiles(melds)
    has_kan = b.n_kans() > 0
    flags = set(flags_force)
    if by is None:
        if flags & {"haitei", "rinshan", "tenhou", "chiihou"}:
            by = "tsumo"
        elif flags & {"houtei", "chankan"}:
            by = "ron"
        else:
            by = "tsumo" if rng.random() < 0.45 else "ron"
    if seat is None:
        seat = rng.choices(WINDS, [30, 25, 25, 20])[0]
    if rnd is None:
        rnd = rng.choices(WINDS, [50, 38, 8, 4])[0]
    if "tenhou" in flags:
        seat = "E"
    if "chiihou" in flags and seat == "E":
        seat = rng.choice("SWN")
    if not no_random_flags and not flags & {"tenhou", "chiihou"}:
        if closed and not flags & {"riichi", "double_riichi"}:
            r = rng.random()
            if r < 0.42:
                flags.add("riichi")
            elif r < 0.47:
                flags.add("double_riichi")
        if flags & {"riichi", "double_riichi"} and rng.random() < 0.22:
            flags.add("ippatsu")
        if by == "tsumo":
            if has_kan and "ippatsu" not in flags and rng.random() < 0.2:
                flags.add("rinshan")
            elif rng.random() < 0.04:
                flags.add("haitei")
        else:
            if rng.random() < 0.04:
                flags.add("houtei")
            elif counts34(all_tiles)[kind(win)] == 1 and rng.random() < 0.05:
                flags.add("chankan")
        if closed and not melds and by == "tsumo" and not flags and rng.random() < 0.015:
            flags.add("tenhou" if seat == "E" else "chiihou")
    # validity
    if flags & {"riichi", "double_riichi", "ippatsu", "tenhou", "chiihou"} and not closed:
        return None
    if flags & {"tenhou", "chiihou"} and (melds or by != "tsumo"):
        return None
    if "rinshan" in flags and (not has_kan or by != "tsumo" or "ippatsu" in flags or "haitei" in flags):
        return None
    if "chankan" in flags and (by != "ron" or counts34(all_tiles)[kind(win)] != 1 or "houtei" in flags):
        return None
    if "haitei" in flags and by != "tsumo":
        return None
    if "houtei" in flags and by != "ron":
        return None
    if "ippatsu" in flags and not flags & {"riichi", "double_riichi"}:
        return None
    if "ippatsu" in flags and "chankan" in flags:
        return None  # the robbed shouminkan is a call, which ends ippatsu (spec/rules.md)
    # dora from the tiles this player can't see
    pool = Pool(rng)
    pool.add_existing(all_tiles)
    n_ind = 1 + b.n_kans() + (1 if rng.random() < 0.1 else 0)
    n_ind = min(n_ind, 5)
    dora = []
    for _ in range(n_ind):
        dora.append(pool.random_tile())
    ura = []
    if flags & {"riichi", "double_riichi"}:
        for _ in range(n_ind):
            ura.append(pool.random_tile())
    if honba is None:
        honba = rng.choices([0, 1, 2, 3, 4, 5, 8], [62, 16, 9, 6, 3, 3, 1])[0]
    pairs = hm(hand, melds) + [("win", fmt_tile(win)), ("by", by), ("seat", seat), ("round", rnd)]
    if dora:
        pairs.append(("dora", fmt_tiles(dora)))
    if ura:
        pairs.append(("ura", fmt_tiles(ura)))
    if honba:
        pairs.append(("honba", str(honba)))
    if flags:
        order = ["double_riichi", "riichi", "ippatsu", "haitei", "houtei", "rinshan", "chankan", "tenhou", "chiihou"]
        pairs.append(("flags", ",".join(f for f in order if f in flags)))
    return pairs


# ---------------------------------------------------------------- oracle-test requests


def load_test_requests(op):
    path = os.path.join(HERE, "oracle_test_requests.txt")
    if not os.path.exists(path):
        return []
    out = []
    with open(path) as f:
        for line in f:
            line = line.rstrip("\n")
            if not line or line.startswith("#"):
                continue
            tag, rest = line.split("\t", 1)
            rop, body = rest.split(" ", 1)
            if rop == op:
                out.append((tag, body))
    return out


def emit_test_requests(e: Emitter, op):
    reqs = load_test_requests(op)
    if not reqs:
        return 0
    e.section(f"hands from the oracle library's own tests (tests/), re-scored under the shootout rules")
    n = 0
    for tag, body in reqs:
        pairs = [tuple(t.split("=", 1)) for t in body.split(" ")]
        if e.emit(pairs, comments=[f"from {tag}"]) is not None:
            n += 1
    return n


