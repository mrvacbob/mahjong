def gen_waits(rng, out):
    e = Emitter(os.path.join(out, "waits.txt"), "wa", "waits", ["waits: tiles that lower shanten, and their live count."])

    def minus_one(b):
        c = b.concealed()
        c.pop(rng.randrange(len(c)))
        return c

    e.section("tenpai hands: complete hand minus one tile, mixed styles and melds")
    for _ in guard(e, 800):
        b, _ = any_built(rng)
        e.emit(hm(minus_one(b), b.melds))
    e.section("single-suit tenpai (multi-sided waits)")
    target = e.count + 300
    for _ in guard(e, target):
        b = style_build(rng, "chinitsu")
        if b is None:
            continue
        if rng.random() < 0.8:
            assign_melds(rng, b, 0, 0)
        e.emit(hm(minus_one(b), b.melds))
    e.section("chiitoi, kokushi and chuuren tenpai")
    target = e.count + 70
    for _ in guard(e, target):
        b = build_chiitoi(rng, dup_seq=rng.random() < 0.3)
        if b:
            e.emit(hm(minus_one(b), []))
    target = e.count + 50
    for _ in guard(e, target):
        b = build_kokushi(rng)
        e.emit(hm(minus_one(b), []))
    target = e.count + 30
    for _ in guard(e, target):
        b = build_chuuren(rng)
        e.emit(hm(minus_one(b), []))
    e.section("one tile further: tenpai hand with one tile replaced")
    target = e.count + 400
    for _ in guard(e, target):
        b, _ = any_built(rng)
        c = b.concealed()
        t = c.pop(rng.randrange(len(c)))
        b.pool.counts[kind(t)] -= 1
        b.pool.red_used.discard(t)
        e.emit(hm(perturb(rng, c, b.pool, 1), b.melds))
    e.section("waits blocked by own tiles (kinds whose four copies are all visible)")
    target = e.count + 60
    tries = 0
    for _ in guard(e, target):
        tries += 1
        b = build(rng, seq_prob=0.35, group_ok=suit_ok(rng.randrange(3), True) if rng.random() < 0.5 else None)
        if b is None:
            continue
        nopen = rng.choices([0, 1, 2], [60, 25, 15])[0]
        assign_melds(rng, b, nopen, 0, kan_prob=0.5)
        c = minus_one(b)
        base, tiles, _ = O.waits(c, b.melds)
        vis = counts34(c + meld_tiles(b.melds))
        # would a fully visible kind have lowered shanten?
        blocked = [k for k in range(34) if vis[k] >= 4 and O.shanten_all(c + [k], b.melds)[3] < base]
        if blocked:
            e.emit(hm(c, b.melds), comments=[f"fully visible kinds that would otherwise count: {fmt_tiles(blocked)}"])
    e.section("random hands")
    target = e.count + 250
    for _ in guard(e, target):
        pool = Pool(rng)
        melds = []
        for _ in range(rng.choices([0, 1, 2], [75, 15, 10])[0]):
            k = rng.randrange(34)
            if pool.can(k, 3):
                melds.append(("p", [pool.take(k) for _ in range(3)]))
        tiles, _ = random_tiles(rng, 13 - 3 * len(melds), pool=pool)
        e.emit(hm(tiles, melds))
    emit_test_requests(e, "waits")
    e.write()
    return e


